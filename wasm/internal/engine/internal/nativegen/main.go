// Command nativegen writes the engine's native handlers: machine code for
// the hot operations of register code, run over the same instructions and
// frames as the Go handlers (wasm/internal/engine/README.md, "Native
// handlers"). It writes native_handlers_amd64.s and native_handlers_arm64.s:
// each architecture's handlers' block, one TEXT symbol of BYTE directives
// (WORD directives on arm64, whose assembler takes nothing else),
// position-independent, every address it needs in the context it is given;
// and the native tables, each operation's handler's address, the exit
// stub's where it has none.
//
// Usage: go run ./wasm/internal/engine/internal/nativegen AMD64-OUTPUT ARM64-OUTPUT
package main

import (
	"bytes"
	"encoding/binary"
	"fmt"
	"os"
	"strings"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: nativegen AMD64-OUTPUT ARM64-OUTPUT")
		os.Exit(2)
	}
	for i, emit := range []func() (*block, error){emitAMD64, emitARM64} {
		b, err := emit()
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		if err := os.WriteFile(os.Args[1+i], b.source(), 0o644); err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
	}
}

// block is an architecture's handlers: its code, the offset of each
// operation's handler, the entry's and the exit stub's.
type block struct {
	code        []byte
	at          map[int]int
	names       map[int]string
	order       []int
	entry, exit int
	// extAt and extNames are the second table's handlers, by X.
	extAt    map[int]int
	extNames map[int]string
	// simdAt and simdNames are rSIMD's table's handlers, by X.
	simdAt    map[int]int
	simdNames map[int]string
	// words says the code is written as 32-bit words (arm64's), not bytes.
	words bool
}

// source is the block's file.
func (b *block) source() []byte {
	var s bytes.Buffer
	s.WriteString("// Code generated by nativegen (wasm/internal/engine/internal/nativegen). DO NOT EDIT.\n\n#include \"textflag.h\"\n\n")
	ctx := "DI"
	if b.words {
		ctx = "R25"
	}
	fmt.Fprintf(&s, "// wasmNativeHandlers is register code's native handlers, %d bytes of\n", len(b.code))
	fmt.Fprintf(&s, "// position-independent machine code: every address it needs is in the\n// context it is given in %s. Its entry is at 0, the exit stub at ", ctx)
	fmt.Fprintf(&s, "%d, and its\n// handlers, in order:\n//\n", b.exit)
	for _, op := range b.order {
		fmt.Fprintf(&s, "//\t%5d  %s\n", b.at[op], b.names[op])
	}
	s.WriteString("TEXT ·wasmNativeHandlers(SB), NOSPLIT|NOFRAME, $0-0\n")
	// The block is padded to whole 4 KB pages -- with INT3 on amd64, UDF
	// on arm64 -- so that a change to the handlers moves none of the code
	// after it within its page: what follows is the package's closures,
	// some of them hot in Go's handlers, whose speed moves with where they
	// lie.
	code := b.code
	pad := byte(0xcc)
	if b.words {
		pad = 0
	}
	for len(code)%4096 != 0 {
		code = append(code, pad)
	}
	for i := 0; i < len(code); i += 16 {
		var parts []string
		line := code[i:min(i+16, len(code))]
		if b.words {
			for j := 0; j < len(line); j += 4 {
				parts = append(parts, fmt.Sprintf("WORD $0x%08x", binary.LittleEndian.Uint32(line[j:])))
			}
		} else {
			for _, c := range line {
				parts = append(parts, fmt.Sprintf("BYTE $0x%02x", c))
			}
		}
		s.WriteString("\t" + strings.Join(parts, "; ") + "\n")
	}
	s.WriteString("\n// wasmNativeTable is the native table: each operation's handler's\n// address, the exit stub's where it has none.\n")
	for op := 0; op < 256; op++ {
		off, ok := b.at[op]
		if !ok {
			off = b.exit
		}
		fmt.Fprintf(&s, "DATA ·wasmNativeTable+%d(SB)/8, $·wasmNativeHandlers+%d(SB)\n", 8*op, off)
	}
	s.WriteString("GLOBL ·wasmNativeTable(SB), RODATA, $2048\n")
	s.WriteString("\n// wasmNativeExtTable is the native second table, rExt's: each operation's\n// handler's address, the exit stub's where it has none.\n")
	for x := 0; x < 256; x++ {
		off, ok := b.extAt[x]
		if !ok {
			off = b.exit
		} else {
			fmt.Fprintf(&s, "// %d: %s\n", x, b.extNames[x])
		}
		fmt.Fprintf(&s, "DATA ·wasmNativeExtTable+%d(SB)/8, $·wasmNativeHandlers+%d(SB)\n", 8*x, off)
	}
	s.WriteString("GLOBL ·wasmNativeExtTable(SB), RODATA, $2048\n")
	s.WriteString("\n// wasmNativeSIMDTable is rSIMD's native table: each operator's handler's\n// address, the exit stub's where it has none.\n")
	for x := 0; x < 256; x++ {
		off, ok := b.simdAt[x]
		if !ok {
			off = b.exit
		} else {
			fmt.Fprintf(&s, "// %d: %s\n", x, b.simdNames[x])
		}
		fmt.Fprintf(&s, "DATA ·wasmNativeSIMDTable+%d(SB)/8, $·wasmNativeHandlers+%d(SB)\n", 8*x, off)
	}
	s.WriteString("GLOBL ·wasmNativeSIMDTable(SB), RODATA, $2048\n")
	return s.Bytes()
}
