package main

import (
	"bytes"
	"fmt"
	"os"
)

// Register code's SIMD operations (README.md, "The opcode space"): each
// operator a value of rSIMD's table, its X, its handler calling the
// operator's function on the frame's slots:
//
//	unary    v128 A = op v128 B
//	binary   v128 A = op v128 B, v128 C
//	ternary  v128 A = op v128 B, v128 C, v128 D (D in the word after)
//	shift    v128 A = op v128 B, i32 C
//	test     i32 A = op v128 B

func regHandler(b *bytes.Buffer, o op) {
	fmt.Fprintf(b, "func rhS%s(l unsafe.Pointer, w uint64, pc int32, f *frame) int32 {\n", o.name)
	fn := o.function()
	switch o.kind {
	case unary:
		fmt.Fprintf(b, "setV(l, w>>16, %s(rv(l, w>>32)))\nreturn pc + 1\n", fn)
	case binary:
		fmt.Fprintf(b, "setV(l, w>>16, %s(rv(l, w>>32), rv(l, w>>48)))\nreturn pc + 1\n", fn)
	case ternary:
		fmt.Fprintf(b, "setV(l, w>>16, %s(rv(l, w>>32), rv(l, w>>48), rv(l, f.rc.code[pc+1])))\nreturn pc + 2\n", fn)
	case shift:
		fmt.Fprintf(b, "setV(l, w>>16, %s(rv(l, w>>32), uint32(*rs(l, w>>48))))\nreturn pc + 1\n", fn)
	case test:
		fmt.Fprintf(b, "*rs(l, w>>16) = uint64(%s(rv(l, w>>32)))\nreturn pc + 1\n", fn)
	}
	b.WriteString("}\n\n")
}

func writeReg(path string, all []op) {
	if len(all) > 256-regReserved {
		fmt.Fprintf(os.Stderr, "simdgen: %d operators do not fit rSIMD's table\n", len(all))
		os.Exit(1)
	}
	var b bytes.Buffer
	b.WriteString(`// Code generated by internal/simdgen; DO NOT EDIT.

package engine

import (
	"unsafe"

	"github.com/go-quickjs/go-quickjs/wasm/internal/opcode"
)

// The SIMD operators of register code, their values in rSIMD's table.
const (
`)
	for i, o := range all {
		if i == 0 {
			fmt.Fprintf(&b, "s%s regOp = iota\n", o.name)
		} else {
			fmt.Fprintf(&b, "s%s\n", o.name)
		}
	}
	b.WriteString("// regSIMDGenCount is the number of values the generated operators take.\nregSIMDGenCount\n)\n\n")
	for _, o := range all {
		regHandler(&b, o)
	}
	b.WriteString(`// regSIMDOp returns the value in rSIMD's table of SIMD operator op and
// its signature, reporting whether op is one of the generated operators.
func regSIMDOp(op opcode.Opcode) (regOp, int, bool) {
	switch op {
`)
	kinds := map[kind]string{unary: "simdUnary", binary: "simdBinary", ternary: "simdTernary", shift: "simdShift", test: "simdTest"}
	for _, o := range all {
		fmt.Fprintf(&b, "case opcode.%s:\nreturn s%s, %s, true\n", o.name, o.name, kinds[o.kind])
	}
	b.WriteString("}\nreturn 0, 0, false\n}\n\nfunc init() {\n")
	for _, o := range all {
		fmt.Fprintf(&b, "regSIMDTable[s%s] = rhS%s\n", o.name, o.name)
	}
	b.WriteString("}\n")
	writeFile(path, b.Bytes())
}

// regReserved is the number of rSIMD's values the hand-written operations
// take, after the generated ones.
const regReserved = 24
