// Package snapgen writes internal/vm's jit_snapshot_gen.go from
// jitFeedback's methods, which it reads from the package's source: the
// snapshot of a build's feedback asked ahead (jit_snapshot.go), its
// answer to each method and its asker of each method of a PC. A method
// added to jitFeedback is then a method of the feedback and of its
// snapshot, which the build may ask either of: written by hand, the two would
// drift from the feedback, the snapshot answering a question it was never
// asked. And the same of register code's feedback, jitRegFeedback's
// methods: the register snapshot's (jitRegSnapshot, jit_snap.go),
// which has those methods alone, as the build finds what a feedback
// answers by the methods it has, and its askers.
package snapgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// A method is one of jitFeedback's: its name, its parameters as written,
// its parameters' names and types, and its results' types.
type method struct {
	name, params  string
	pnames, ptype []string
	results       []string
}

// atPC reports whether the method's argument is a PC: a program's, or, a
// register feedback's rpc, its register code's.
func (m method) atPC() bool {
	return len(m.pnames) == 1 && (m.pnames[0] == "pc" || m.pnames[0] == "rpc") && m.ptype[0] == "int"
}

// methods are recv's exported methods in dir's JIT files, jit.go and
// jit_*.go, by file name and then by position.
func methods(dir, recv string) ([]method, error) {
	files, err := filepath.Glob(filepath.Join(dir, "jit_*.go"))
	if err != nil {
		return nil, err
	}
	files = append(files, filepath.Join(dir, "jit.go"))
	sort.Strings(files)
	fset := token.NewFileSet()
	var out []method
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") || strings.HasSuffix(file, "_gen.go") {
			continue
		}
		f, err := parser.ParseFile(fset, file, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || !fd.Name.IsExported() || !receiverIs(fd, recv) {
				continue
			}
			m := method{name: fd.Name.Name}
			var params []string
			for _, p := range fd.Type.Params.List {
				t := expr(fset, p.Type)
				for _, n := range p.Names {
					m.pnames = append(m.pnames, n.Name)
					m.ptype = append(m.ptype, t)
				}
				names := make([]string, len(p.Names))
				for i, n := range p.Names {
					names[i] = n.Name
				}
				params = append(params, strings.Join(names, ", ")+" "+t)
			}
			m.params = strings.Join(params, ", ")
			if fd.Type.Results != nil {
				for _, r := range fd.Type.Results.List {
					t := expr(fset, r.Type)
					n := max(len(r.Names), 1)
					for range n {
						m.results = append(m.results, t)
					}
				}
			}
			out = append(out, m)
		}
	}
	return out, nil
}

// receiverIs reports whether fd is a method of *name.
func receiverIs(fd *ast.FuncDecl, name string) bool {
	star, ok := fd.Recv.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	id, ok := star.X.(*ast.Ident)
	return ok && id.Name == name
}

func expr(fset *token.FileSet, e ast.Expr) string {
	var b bytes.Buffer
	printer.Fprint(&b, fset, e)
	return b.String()
}

const header = `//go:build quickjs_jit && !android && !ios && ((linux && amd64) || (windows && amd64) || ((darwin || linux) && arm64))

// Code generated by internal/vm/internal/snapgen from jitRegFeedback's
// methods; DO NOT EDIT. Run go generate ./internal/vm.

package vm

import "github.com/go-quickjs/go-quickjs/internal/jit/ssa"

`

// Generate is jit_snapshot_gen.go for the package in dir.
func Generate(dir string) (snapshot []byte, err error) {
	ms, err := methods(dir, "jitRegFeedback")
	if err != nil {
		return nil, err
	}
	if len(ms) > 64 {
		return nil, fmt.Errorf("%d methods: the snapshot's sets of them are 64 bits", len(ms))
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("// The methods, numbered.\nconst (\n")
	for i, m := range ms {
		if i == 0 {
			fmt.Fprintf(&b, "\tsnap%s jitSnapMethod = iota\n", m.name)
		} else {
			fmt.Fprintf(&b, "\tsnap%s\n", m.name)
		}
	}
	b.WriteString(")\n\n// jitSnapAtPC says which methods' argument is a PC.\nvar jitSnapAtPC = [...]bool{")
	for i, m := range ms {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprint(&b, m.atPC())
	}
	b.WriteString("}\n\n// jitSnapNames are the methods' names, by jitSnapMethod.\nvar jitSnapNames = [...]string{")
	for i, m := range ms {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", m.name)
	}
	b.WriteString("}\n\n")
	if err := registerSnapshot(&b, ms, ms); err != nil {
		return nil, err
	}
	snapshot, err = format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("jit_snapshot_gen.go: %w", err)
	}
	return snapshot, nil
}

// stateMethods are the methods the build asks by a state's PC, a register
// pc, not a program's instruction's (jitRegSnapStatePC): their answers
// default to none within the register code, and record no use.
var stateMethods = map[string]bool{"Resumed": true, "EntryGeneric": true}

// compileWide are the methods of no argument whose answer is the
// runtime's, the same for every snapshot of a compile: asked of the
// compile's own function's snapshot alone (askOnceReg), whose table its
// callees' snapshots answer from, its effects -- what the root's keep was
// given, the keep of every snapshot of the compile -- used as the root's.
var compileWide = map[string]bool{
	"ArrayProtos": true, "GenNext": true, "HasCache": true, "KeyAtoms": true,
	"MapNexts": true, "TypeofCells": true, "WalkedCloseCell": true,
}

// poolTypes are the results' types an answer names pools of objects in
// (jitSnapPools), which the snapshot asks the roots of.
var poolTypes = map[string]bool{
	"ssa.LiteralSite": true, "ssa.ClosureSite": true, "ssa.InlineSite": true,
	"[]ssa.CallSite": true, "ssa.AccessorSite": true, "ssa.ForEachSite": true,
}

// answered is the test of whether a question of a PC answered something,
// by its last result r of type t: ok, or a list with something in it.
func answered(t, r string) string {
	switch t {
	case "bool":
		return r
	case "[]ssa.GenStep", "[]ssa.CallSite":
		return "len(" + r + ") != 0"
	}
	return "true"
}

// registerSnapshot writes the register snapshot's answers, numbered as
// jitFeedback's methods of the same names, and its askers, of regs,
// jitRegFeedback's methods: each a method of jitFeedback's, which the
// build asks of either form's feedback alike. Each method's answers are
// kept as its results, in a table by argument (jitSnapTable), not boxed.
func registerSnapshot(b *bytes.Buffer, ms, regs []method) error {
	known := map[string]bool{}
	for _, m := range ms {
		known[m.name] = true
	}
	b.WriteString("// jitRegSnapStatePC are the methods the build asks by a state's PC, which\n" +
		"// in a register program is a register pc, not an instruction's (Resumed and\n" +
		"// EntryGeneric): only PCs with a true answer need to be captured.\n" +
		"const jitRegSnapStatePC uint64 = 0")
	for _, m := range regs {
		if stateMethods[m.name] {
			fmt.Fprintf(b, " | 1<<snap%s", m.name)
		}
	}
	b.WriteString("\n\n// The answers' results, by method. Nothing compares them: one of more\n" +
		"// than one result, not all bytes, has a blank field first, since,\n" +
		"// comparable, the padding after its bool had given it an equality\n" +
		"// function the compiler lays out among package vm's code.\n")
	for _, m := range regs {
		if !known[m.name] {
			return fmt.Errorf("jitRegFeedback's %s is no method of jitFeedback's", m.name)
		}
		fmt.Fprintf(b, "type jitSnapAns%s struct {\n", m.name)
		if uncompared(m) {
			b.WriteString("\t_ [0]func()\n")
		}
		for i, t := range m.results {
			fmt.Fprintf(b, "\tr%d %s\n", i, t)
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("// jitSnapAnswers are a snapshot's answers, a table of each method's by\n// their argument.\ntype jitSnapAnswers struct {\n")
	for _, m := range regs {
		fmt.Fprintf(b, "\t%s jitSnapTable[jitSnapAns%s]\n", m.name, m.name)
	}
	b.WriteString("}\n\n// seal sorts the tables put out of their arguments' order.\nfunc (a *jitSnapAnswers) seal() {\n")
	for _, m := range regs {
		fmt.Fprintf(b, "\ta.%s.seal()\n", m.name)
	}
	b.WriteString("}\n\n// answered counts the questions answered.\nfunc (a *jitSnapAnswers) answered() int {\n\treturn 0")
	for _, m := range regs {
		fmt.Fprintf(b, " +\n\t\ta.%s.answered()", m.name)
	}
	b.WriteString("\n}\n\n// pools adds to pools every pool an answer names (jitSnapPools).\nfunc (a *jitSnapAnswers) pools(pools *[]uintptr) {\n")
	for _, m := range regs {
		var named []int
		for i, t := range m.results {
			if poolTypes[t] {
				named = append(named, i)
			}
		}
		if len(named) == 0 {
			continue
		}
		fmt.Fprintf(b, "\tfor i := range a.%s.e {\n\t\tif e := &a.%s.e[i]; e.answered {\n", m.name, m.name)
		for _, i := range named {
			fmt.Fprintf(b, "\t\t\tjitSnapPools(&e.v.r%d, pools)\n", i)
		}
		b.WriteString("\t\t}\n\t}\n")
	}
	b.WriteString("}\n\n// The register snapshot's answers: jitRegFeedback's methods, numbered as\n" +
		"// jitFeedback's of the same names.\n\n")
	for _, m := range regs {
		key := "0"
		if len(m.pnames) > 0 {
			key = "int64(" + m.pnames[0] + ")"
		}
		var named []string
		for i, t := range m.results {
			named = append(named, fmt.Sprintf("r%d %s", i, t))
		}
		fmt.Fprintf(b, "func (q *jitRegSnapshot) %s(%s) (%s) {\n", m.name, m.params, strings.Join(named, ", "))
		// The answers derived first, where the worker has not (ready).
		switch {
		case compileWide[m.name]:
			if len(m.pnames) != 0 {
				panic("snapgen: compile-wide " + m.name + " takes an argument")
			}
			// The compile's own function's answer, its effect used as its.
			fmt.Fprintf(b, "\tq.s.ready()\n\troot := q.s.root\n\te := root.a.%s.find(0)\n", m.name)
			fmt.Fprintf(b, "\tif e != nil && e.eff != 0 {\n\t\troot.used(e.eff)\n\t}\n")
			fmt.Fprintf(b, "\tif e == nil || !e.answered {\n\t\tq.s.absent(snap%s, 0)\n\t\treturn\n\t}\n", m.name)
		case stateMethods[m.name]:
			fmt.Fprintf(b, "\tq.s.ready()\n\te := q.s.a.%s.find(%s)\n", m.name, key)
			fmt.Fprintf(b, "\tif e == nil || !e.answered {\n\t\tq.absent(snap%s, %s)\n\t\treturn\n\t}\n", m.name, key)
		default:
			fmt.Fprintf(b, "\tq.s.ready()\n\te := q.s.a.%s.find(%s)\n", m.name, key)
			fmt.Fprintf(b, "\tif e != nil && e.eff != 0 {\n\t\tq.s.used(e.eff)\n\t}\n")
			fmt.Fprintf(b, "\tif e == nil || !e.answered {\n\t\tq.s.absent(snap%s, %s)\n\t\treturn\n\t}\n", m.name, key)
		}
		var rs []string
		for i, t := range m.results {
			fmt.Fprintf(b, "\tr%d = e.v.r%d\n", i, i)
			// NativeCalls' descriptions are read-only, including across builds.
			if strings.HasPrefix(t, "[]") && t != "[]ssa.CallSite" {
				fmt.Fprintf(b, "\tr%d = jitSnapCopy(r%d)\n", i, i)
			}
			rs = append(rs, fmt.Sprintf("r%d", i))
		}
		fmt.Fprintf(b, "\treturn %s\n}\n\n", strings.Join(rs, ", "))
	}
	b.WriteString("// askOnceReg asks fb the questions of no argument.\nfunc (s *jitSnapshot) askOnceReg(fb *jitRegFeedback) {\n")
	wide := 0
	for _, m := range regs {
		if len(m.pnames) != 0 {
			continue
		}
		if compileWide[m.name] {
			wide++
		}
		rs := results(m)
		// Not a method the worker derives (jitSnapDerived), whose gather
		// copies what its answer is made of instead; a compile-wide one
		// asked of the root alone, which its callees answer from.
		root := ""
		if compileWide[m.name] {
			root = " && s == s.root"
		}
		fmt.Fprintf(b, "\tif jitSnapDerived&(1<<snap%s) == 0%s {\n\t\tbefore := s.begin(fb.fb)\n\t\t%s := fb.%s()\n\t\teff := s.end(fb.fb, before)\n", m.name, root, rs, m.name)
		fmt.Fprintf(b, "\t\tif h := fb.fb.r.jitTest.snapAsked; h != nil {\n\t\t\th(s, snap%s, 0, true, []any{%s})\n\t\t}\n", m.name, rs)
		fmt.Fprintf(b, "\t\ts.a.%s.put(0, eff, true, jitSnapAns%s{%s})\n\t}\n", m.name, m.name, keyed(m))
	}
	if wide != len(compileWide) {
		return fmt.Errorf("compileWide names %d methods, %d of them register methods of no argument", len(compileWide), wide)
	}
	b.WriteString("}\n\n// The askers of the register feedback's methods of a PC, as\n" +
		"// jitSnapAskers's, the callees of the inline sites it names asked in turn\n" +
		"// (nestReg).\n")
	for _, m := range regs {
		if !m.atPC() {
			continue
		}
		rs := results(m)
		fmt.Fprintf(b, "func jitRegSnapAsk%s(s *jitSnapshot, fb *jitRegFeedback, pc int) {\n\tbefore := s.begin(fb.fb)\n\t%s := fb.%s(pc)\n\teff := s.end(fb.fb, before)\n", m.name, rs, m.name)
		for i, t := range m.results {
			switch t {
			case "ssa.InlineSite":
				fmt.Fprintf(b, "\tr%d = s.nestReg(r%d)\n", i, i)
			case "ssa.AccessorSite", "ssa.ForEachSite":
				fmt.Fprintf(b, "\tif r%d.Inline != nil {\n\t\tnested := s.nestReg(*r%d.Inline)\n\t\tr%d.Inline = &nested\n\t}\n", i, i, i)
			}
		}
		last := len(m.results) - 1
		fmt.Fprintf(b, "\tok := %s\n", answered(m.results[last], fmt.Sprintf("r%d", last)))
		fmt.Fprintf(b, "\tif h := fb.fb.r.jitTest.snapAsked; h != nil {\n\t\th(s, snap%s, int64(pc), ok, []any{%s})\n\t}\n", m.name, rs)
		fmt.Fprintf(b, "\tif ok || eff != 0 {\n\t\ts.a.%s.reserve(int(s.room[snap%s]))\n\t\ts.a.%s.put(int64(pc), eff, ok, jitSnapAns%s{%s})\n\t}\n}\n\n", m.name, m.name, m.name, m.name, keyed(m))
	}
	b.WriteString("// jitRegSnapAskers are the register askers by method, nil for one the\n" +
		"// register feedback has not or of another argument.\n" +
		"var jitRegSnapAskers [len(jitSnapNames)]func(s *jitSnapshot, fb *jitRegFeedback, pc int)\n\n" +
		"// jitRegSnapMethods are the methods the register feedback has, a bit\n// for each.\nconst jitRegSnapMethods uint64 = 0")
	for _, m := range regs {
		fmt.Fprintf(b, " |\n\t1<<snap%s", m.name)
	}
	b.WriteString("\n\n// The register askers are set at init, as jitSnapAskers are.\nfunc init() {\n" +
		"\tjitRegSnapAskers = [len(jitSnapNames)]func(s *jitSnapshot, fb *jitRegFeedback, pc int){\n")
	for _, m := range regs {
		if m.atPC() {
			fmt.Fprintf(b, "\t\tsnap%s: jitRegSnapAsk%s,\n", m.name, m.name)
		}
	}
	b.WriteString("\t}\n}\n")
	return nil
}

// results are m's results' names, r0, r1, ...
func results(m method) string {
	var rs []string
	for i := range m.results {
		rs = append(rs, fmt.Sprintf("r%d", i))
	}
	return strings.Join(rs, ", ")
}

// uncompared reports whether m's answer's type has a blank field that
// makes it not comparable: one of more than one result, not all bytes,
// whose padding would have given it an equality function. One of a
// result alone, or of bytes alone, compares as memory, and its blank
// field would have grown it and its table's entries.
func uncompared(m method) bool {
	if len(m.results) < 2 {
		return false
	}
	for _, t := range m.results {
		if t != "bool" && t != "uint8" {
			return true
		}
	}
	return false
}

// keyed is m's results as the fields of its answer's literal, each by its
// name: an answer's type may have a blank field first (uncompared), which
// no literal of its fields in order can leave out.
func keyed(m method) string {
	var rs []string
	for i := range m.results {
		rs = append(rs, fmt.Sprintf("r%d: r%d", i, i))
	}
	return strings.Join(rs, ", ")
}

// Write writes jit_snapshot_gen.go into dir.
func Write(dir string) error {
	snapshot, err := Generate(dir)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "jit_snapshot_gen.go"), snapshot, 0o644)
}
