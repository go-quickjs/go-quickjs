// Package snapgen writes internal/vm's zzjit_snapshot_gen.go and
// zzjit_asked_gen_test.go from jitFeedback's methods, which it reads from
// the package's source: the snapshot of a build's feedback asked ahead
// (zzjit_snapshot.go), its answer to each method and its asker of each
// method of a PC, and the proxy that notes what a build asks
// (zzjit_asked_test.go). A method added to jitFeedback is then a method of
// both, which the build may ask either of: written by hand, the two would
// drift from the feedback, the snapshot answering a question it was never
// asked.
package snapgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// A method is one of jitFeedback's: its name, its parameters as written,
// its parameters' names and types, and its results' types.
type method struct {
	name, params  string
	pnames, ptype []string
	results       []string
}

// atPC reports whether the method's argument is a PC.
func (m method) atPC() bool { return len(m.pnames) == 1 && m.pnames[0] == "pc" && m.ptype[0] == "int" }

// methods are jitFeedback's exported methods in dir's zzjit_*.go files, by
// file name and then by position.
func methods(dir string) ([]method, error) {
	files, err := filepath.Glob(filepath.Join(dir, "zzjit_*.go"))
	if err != nil {
		return nil, err
	}
	sort.Strings(files)
	fset := token.NewFileSet()
	var out []method
	for _, file := range files {
		if strings.HasSuffix(file, "_test.go") || strings.HasSuffix(file, "_gen.go") {
			continue
		}
		f, err := parser.ParseFile(fset, file, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			fd, ok := d.(*ast.FuncDecl)
			if !ok || fd.Recv == nil || !fd.Name.IsExported() || !receiverIs(fd, "jitFeedback") {
				continue
			}
			m := method{name: fd.Name.Name}
			var params []string
			for _, p := range fd.Type.Params.List {
				t := expr(fset, p.Type)
				for _, n := range p.Names {
					m.pnames = append(m.pnames, n.Name)
					m.ptype = append(m.ptype, t)
				}
				names := make([]string, len(p.Names))
				for i, n := range p.Names {
					names[i] = n.Name
				}
				params = append(params, strings.Join(names, ", ")+" "+t)
			}
			m.params = strings.Join(params, ", ")
			if fd.Type.Results != nil {
				for _, r := range fd.Type.Results.List {
					t := expr(fset, r.Type)
					n := max(len(r.Names), 1)
					for range n {
						m.results = append(m.results, t)
					}
				}
			}
			out = append(out, m)
		}
	}
	return out, nil
}

// receiverIs reports whether fd is a method of *name.
func receiverIs(fd *ast.FuncDecl, name string) bool {
	star, ok := fd.Recv.List[0].Type.(*ast.StarExpr)
	if !ok {
		return false
	}
	id, ok := star.X.(*ast.Ident)
	return ok && id.Name == name
}

func expr(fset *token.FileSet, e ast.Expr) string {
	var b bytes.Buffer
	printer.Fprint(&b, fset, e)
	return b.String()
}

const header = `//go:build quickjs_jit && !android && !ios && ((linux && amd64) || (windows && amd64) || (darwin && arm64))

// Code generated by internal/vm/internal/snapgen from jitFeedback's
// methods; DO NOT EDIT. Run go generate ./internal/vm.

package vm

import "github.com/go-quickjs/go-quickjs/internal/jit/ssa"

`

// Generate is zzjit_snapshot_gen.go and zzjit_asked_gen_test.go for the
// package in dir.
func Generate(dir string) (snapshot, asked []byte, err error) {
	ms, err := methods(dir)
	if err != nil {
		return nil, nil, err
	}
	if len(ms) > 64 {
		return nil, nil, fmt.Errorf("%d methods: the snapshot's sets of them are 64 bits", len(ms))
	}
	var b bytes.Buffer
	b.WriteString(header)
	b.WriteString("// The methods, numbered.\nconst (\n")
	for i, m := range ms {
		if i == 0 {
			fmt.Fprintf(&b, "\tsnap%s jitSnapMethod = iota\n", m.name)
		} else {
			fmt.Fprintf(&b, "\tsnap%s\n", m.name)
		}
	}
	b.WriteString(")\n\n// jitSnapAtPC says which methods' argument is a PC.\nvar jitSnapAtPC = [...]bool{")
	for i, m := range ms {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprint(&b, m.atPC())
	}
	b.WriteString("}\n\n// jitSnapNames are the methods' names, by jitSnapMethod.\nvar jitSnapNames = [...]string{")
	for i, m := range ms {
		if i > 0 {
			b.WriteString(", ")
		}
		fmt.Fprintf(&b, "%q", m.name)
	}
	b.WriteString("}\n\n")
	// The answers.
	for _, m := range ms {
		key := "0"
		if len(m.pnames) > 0 {
			key = "int64(" + m.pnames[0] + ")"
		}
		var named []string
		for i, t := range m.results {
			named = append(named, fmt.Sprintf("r%d %s", i, t))
		}
		fmt.Fprintf(&b, "func (s *jitSnapshot) %s(%s) (%s) {\n", m.name, m.params, strings.Join(named, ", "))
		fmt.Fprintf(&b, "\ta := s.get(snap%s, %s)\n\tif a == nil {\n\t\treturn\n\t}\n", m.name, key)
		var rs []string
		for i, t := range m.results {
			fmt.Fprintf(&b, "\tr%d, _ = a[%d].(%s)\n", i, i, t)
			if strings.HasPrefix(t, "[]") {
				fmt.Fprintf(&b, "\tr%d = jitSnapCopy(r%d)\n", i, i)
			}
			rs = append(rs, fmt.Sprintf("r%d", i))
		}
		fmt.Fprintf(&b, "\treturn %s\n}\n\n", strings.Join(rs, ", "))
	}
	// The askers.
	b.WriteString("// askOnce asks fb the questions of no argument.\nfunc (s *jitSnapshot) askOnce(fb *jitFeedback) {\n")
	for _, m := range ms {
		if len(m.pnames) != 0 {
			continue
		}
		rs := results(m)
		fmt.Fprintf(&b, "\t{\n\t\tbefore := s.begin(fb)\n\t\t%s := fb.%s()\n\t\ts.end(fb, before, snap%s, 0)\n\t\ts.put(snap%s, 0, %s)\n\t}\n", rs, m.name, m.name, m.name, rs)
	}
	b.WriteString("}\n\n// The askers of the methods of a PC, each asking fb its method at pc and\n" +
		"// keeping what it answers, the callees of the inline sites it names asked in\n" +
		"// turn (nest).\n")
	for _, m := range ms {
		if !m.atPC() {
			continue
		}
		rs := results(m)
		fmt.Fprintf(&b, "func jitSnapAsk%s(s *jitSnapshot, fb *jitFeedback, pc int) {\n\tbefore := s.begin(fb)\n\t%s := fb.%s(pc)\n\ts.end(fb, before, snap%s, int64(pc))\n", m.name, rs, m.name, m.name)
		nests(&b, m, "\t")
		fmt.Fprintf(&b, "\tif jitSnapAnswered(r%d) {\n\t\ts.put(snap%s, int64(pc), %s)\n\t}\n}\n\n", len(m.results)-1, m.name, rs)
	}
	b.WriteString("// jitSnapAskers are the askers by method, nil for one of another argument.\n" +
		"var jitSnapAskers [len(jitSnapNames)]func(s *jitSnapshot, fb *jitFeedback, pc int)\n\n" +
		"// The askers are set at init: through nest, they ask by this table.\nfunc init() {\n" +
		"\tjitSnapAskers = [len(jitSnapNames)]func(s *jitSnapshot, fb *jitFeedback, pc int){\n")
	for _, m := range ms {
		if m.atPC() {
			fmt.Fprintf(&b, "\t\tsnap%s: jitSnapAsk%s,\n", m.name, m.name)
		}
	}
	b.WriteString("\t}\n}\n")
	snapshot, err = format.Source(b.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("zzjit_snapshot_gen.go: %w", err)
	}

	// The proxy that notes what a build asks.
	b.Reset()
	b.WriteString(header)
	for _, m := range ms {
		rs := results(m)
		key := "0"
		if len(m.pnames) > 0 {
			key = "int64(" + m.pnames[0] + ")"
		}
		fmt.Fprintf(&b, "func (q *jitAsked) %s(%s) (%s) {\n\tbefore := q.counts()\n", m.name, m.params, strings.Join(m.results, ", "))
		if rs != "" {
			fmt.Fprintf(&b, "\t%s := q.fb.%s(%s)\n", rs, m.name, strings.Join(m.pnames, ", "))
		}
		for i, t := range m.results {
			switch t {
			case "ssa.InlineSite":
				fmt.Fprintf(&b, "\tr%d = q.wrapSite(r%d)\n", i, i)
			case "ssa.AccessorSite", "ssa.ForEachSite":
				fmt.Fprintf(&b, "\tif r%d.Inline != nil {\n\t\tsite := q.wrapSite(*r%d.Inline)\n\t\tr%d.Inline = &site\n\t}\n", i, i, i)
			}
		}
		fmt.Fprintf(&b, "\tq.note(%q, before, %s, %s)\n\treturn %s\n}\n\n", m.name, key, rs, rs)
	}
	asked, err = format.Source(b.Bytes())
	if err != nil {
		return nil, nil, fmt.Errorf("zzjit_asked_gen_test.go: %w", err)
	}
	return snapshot, asked, nil
}

// results are m's results' names, r0, r1, ...
func results(m method) string {
	var rs []string
	for i := range m.results {
		rs = append(rs, fmt.Sprintf("r%d", i))
	}
	return strings.Join(rs, ", ")
}

// nests writes, for each of m's results that is an inline site or holds
// one, its callee's feedback made a snapshot (nest).
func nests(b *bytes.Buffer, m method, indent string) {
	for i, t := range m.results {
		switch t {
		case "ssa.InlineSite":
			fmt.Fprintf(b, "%sr%d = s.nest(r%d)\n", indent, i, i)
		case "ssa.AccessorSite", "ssa.ForEachSite":
			fmt.Fprintf(b, "%sif r%d.Inline != nil {\n%s\tnested := s.nest(*r%d.Inline)\n%s\tr%d.Inline = &nested\n%s}\n", indent, i, indent, i, indent, i, indent)
		}
	}
}

// Write writes both files into dir.
func Write(dir string) error {
	snapshot, asked, err := Generate(dir)
	if err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(dir, "zzjit_snapshot_gen.go"), snapshot, 0o644); err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, "zzjit_asked_gen_test.go"), asked, 0o644)
}
