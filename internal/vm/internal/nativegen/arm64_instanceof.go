// instanceOf is instanceof by ordinaryHasInstance, as amd64's
// (amd64_instanceof.go).
func (g *armGen) instanceOf() {
	a := g.a
	scan, next, found, loop, yes, no, store := a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel()
	check, miss, value := a.NewLabel(), a.NewLabel(), a.NewLabel()
	g.regC(rD)
	g.object(rS, rD)
	g.last = append(g.last, func() { g.instanceOfSite(check, miss, value) })
	a.Store(rCtx, scr(sE), rS)
	// The site, Aux[pc]: &ic[Aux[pc]].
	a.Load(r8, rCtx, ncRC)
	a.Load(r8, r8, offRCAux)
	a.Cbz(r8, g.exit, true)
	a.Load(r9, rCtx, ncCodeBase)
	a.Op(Sub, rC, rIP, r9, true)
	a.ShiftImm(Lsr, rC, rC, 1, true)
	a.Op(Add, r8, r8, rC, true)
	a.LoadU32(rC, r8, 0)
	a.MovImm(rT, uint64(size("propCache")))
	a.Mul(rC, rC, rT)
	a.Op(Add, rC, rC, rIC, true)
	// Symbol.hasInstance, the realm's.
	g.readSlot(check, miss)
	a.Load(r8, rC, 0)
	g.cmpMem(r8, rCtx, ncObjBits)
	a.BCond(NE, g.exit)
	a.Load(r8, rC, 8)
	a.Load(r9, rCtx, ncRT)
	a.Load(r9, r9, rtRel(0))
	g.addMem(r9, rCtx, ncHasInst)
	g.cmpMem(r8, r9, 0)
	a.BCond(NE, g.exit)
	// A function, not bound.
	a.Load(rS, rCtx, scr(sE))
	a.LoadU16(rD, rS, offObjFlags)
	a.TstImm(rD, uint64(objHasData), false)
	a.BCond(EQ, g.exit)
	a.Load(rD, rS, sizeObj+offExtData)
	g.cmpMem(rD, rCtx, ncFuncT)
	a.BCond(NE, g.exit)
	a.Load(r9, rS, sizeObj+offExtData+8)
	a.LoadU8(rD, r9, offFDBound)
	a.Cbnz(rD, g.exit, false)
	// Its own prototype, a data property holding an object, found in its
	// table, at most 16 keys in.
	a.LoadU32(rD, rS, off("Object.valn"))
	a.CmpImm(rD, 16, true)
	a.BCond(HI, g.exit)
	a.Load(r9, rS, offObjShape)
	a.Cbz(r9, g.exit, true)
	a.Load(r9, r9, off("shape.keys"))
	a.MovImm(rC, 0)
	a.Bind(scan)
	a.Cmp(rC, rD, true)
	a.BCond(HS, g.exit)
	a.MovImm(rT, uint64(size("propKey")))
	a.Mul(r8, rC, rT)
	a.Op(Add, r8, r8, r9, true)
	a.LoadU32(rT, r8, off("propKey.key"))
	a.MovImm(rJ, uint64(uint32(atomPrototype)))
	a.Cmp(rT, rJ, false)
	a.BCond(NE, next)
	a.LoadU8(rT, r8, off("propKey.flags"))
	a.TstImm(rT, uint64(uint8(propOddKey)), false)
	a.BCond(EQ, found)
	a.B(g.exit)
	a.Bind(next)
	a.AddImm(rC, rC, 1, true)
	a.B(scan)
	a.Bind(found)
	a.Load(r8, rS, off("Object.valp"))
	a.AddLsl(rC, r8, rC, 4)
	a.Load(r8, rC, 0)
	g.cmpMem(r8, rCtx, ncObjBits)
	a.BCond(NE, g.exit)
	a.Load(rC, rC, 8)
	// The value: a primitive is no instance; an object's prototypes are
	// walked, a proxy's trap left to Go.
	a.Bind(value)
	a.Load(rW, rIP, 0)
	g.regB(rD)
	a.Load(r9, rD, 0)
	g.cmpMem(r9, rCtx, ncObjBits)
	a.BCond(NE, no)
	a.Load(r8, rD, 8)
	a.Bind(loop)
	a.LoadU8(rT, r8, offObjClass)
	a.CmpImm(rT, int64(ClassProxy), false)
	a.BCond(EQ, g.exit)
	poly, have := a.NewLabel(), a.NewLabel()
	a.LoadU16(rT, r8, offObjFlags)
	a.TstImm(rT, uint64(objPolyProto), false)
	a.BCond(NE, poly)
	a.Load(r8, r8, offObjShape)
	a.Cbz(r8, no, true)
	a.Load(r8, r8, offShapeProto)
	a.B(have)
	a.Bind(poly)
	a.Load(r8, r8, off("Object.valp"))
	a.Load(r8, r8, 8)
	a.Bind(have)
	a.Cbz(r8, no, true)
	a.Cmp(r8, rC, true)
	a.BCond(EQ, yes)
	a.B(loop)
	a.Bind(yes)
	a.LoadF(0, rCtx, ncTrue)
	a.B(store)
	a.Bind(no)
	a.LoadF(0, rCtx, ncFalse)
	a.Bind(store)
	g.storeA(0)
}

// instanceOfSite uses the prototype slot cached by noteInstanceOfSite.
// The site's shape proves an immutable inherited Symbol.hasInstance and
// a plain prototype property. The function's identity need not match:
// its kind and bound flag are checked, and its prototype read anew.
func (g *armGen) instanceOfSite(check, miss, value Label) {
	a := g.a
	a.Bind(check)
	uncached := a.NewLabel()
	a.LoadU16(rD, rC, off("propCache.instanceProto"))
	a.Cbz(rD, uncached, false)
	a.Load(r8, rS, offObjShape)
	g.cmpMem(r8, rC, off("propCache.shape"))
	a.BCond(NE, uncached)
	// A shape can be shared with a bound function or a non-function.
	a.LoadU16(r8, rS, offObjFlags)
	a.TstImm(r8, uint64(objHasData), false)
	a.BCond(EQ, uncached)
	a.Load(r8, rS, sizeObj+offExtData)
	g.cmpMem(r8, rCtx, ncFuncT)
	a.BCond(NE, uncached)
	a.Load(r9, rS, sizeObj+offExtData+8)
	a.LoadU8(r8, r9, offFDBound)
	a.Cbnz(r8, uncached, false)
	a.AddImm(rD, rD, -1, true)
	a.Load(r8, rS, off("Object.valp"))
	a.AddLsl(rC, r8, rD, 4)
	a.Load(r8, rC, 0)
	g.cmpMem(r8, rCtx, ncObjBits)
	a.BCond(NE, g.exit)
	a.Load(rC, rC, 8)
	a.B(value)
	a.Bind(uncached)
	a.Load(r8, rC, off("propCache.ownShape"))
	g.cmpMem(r8, rS, offObjShape)
	a.B(miss)
}

// derivedRet is derived_ret, as amd64's.
func (g *armGen) derivedRet() {
	a := g.a
	done := a.NewLabel()
	g.regA(rD)
	a.Load(r9, rD, 0)
	g.cmpMem(r9, rCtx, ncUndef)
	a.BCond(NE, done)
	a.Load(r9, rD, 8)
	a.Cbnz(r9, done, true)
	a.Load(rS, rCtx, ncNF)
	a.Load(rS, rS, offFThisRef)
	a.Cbz(rS, g.exit, true)
	a.LoadU8(r9, rS, off("thisBinding.init"))
	a.Cbz(r9, g.exit, false)
	a.Load(r9, rS, off("thisBinding.value"))
	a.Load(r8, rS, off("thisBinding.value")+8)
	a.MovRR(rW, rD)
	g.storeValue()
	a.Bind(done)
	g.next()
}

// argsIndex is args_index, as amd64's.
func (g *armGen) argsIndex() {
	a := g.a
	g.regB(rD)
	a.Load(r9, rD, 0)
	g.cmpMem(r9, rCtx, ncObjBits)
	a.BCond(EQ, g.exit)
	g.regC(rD)
	g.num(0, rD)
	a.Fcvtzs(rC, 0)
	a.ShiftImm(Lsr, rT, rC, 32, true)
	a.Cbnz(rT, g.exit, true)
	a.Scvtf(1, rC, true)
	a.FCmp(0, 1)
	a.BCond(NE, g.exit)
	a.Load(rS, rCtx, ncNF)
	g.cmpMem(rC, rS, offFArgs+8)
	a.BCond(HS, g.exit)
	a.Load(r8, rCtx, ncRC)
	a.LoadS32(r9, r8, offRCParams)
	a.Cmp(rC, r9, true)
	a.BCond(LT, g.exit)
	a.Load(r8, rS, offFArgs)
	a.AddLsl(rC, r8, rC, 4)
	a.Load(r9, rC, 0)
	a.Load(r8, rC, 8)
	g.regA(rW)
	g.storeValue()
}
