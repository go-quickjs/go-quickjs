// binaryLeaf answers a numeric binary leaf, this getter or typeof predicate
// without a frame. rC is the cache, rS the window, r8 the code and r9 the closure, as at call's
// upvalue-leaf check. Every failure leaves the call's window untouched.
func (g *armGen) binaryLeaf(start, miss Label) {
	a := g.a
	a.Bind(start)
	a.Load(rJ, r8, off("regCode.leafNative"))
	a.Cbz(rJ, miss, true)
	a.MovRR(rK, r9)
	a.Load(r8, rCtx, ncRT)
	g.cmpMemImm(r8, offRtInterrupt, 1)
	a.BCond(LE, miss)
	getter := a.NewLabel()
	a.Ubfx(rD, rJ, 0, 8)
	a.CmpImm(rD, int64(bytecode.RGetProp), true)
	a.BCond(EQ, getter)
	predicate := a.NewLabel()
	a.CmpImm(rD, int64(bytecode.RJTypeof), true)
	a.BCond(EQ, predicate)
	for i, shift := range []uint8{8, 32} {
		up, ready := a.NewLabel(), a.NewLabel()
		a.Ubfx(rD, rJ, shift, 17)
		a.TstImm(rD, 1<<16, true)
		a.BCond(NE, up)
		a.Ubfx(r9, rW, 8, 8)
		a.Cmp(rD, r9, true)
		a.BCond(HS, miss)
		a.AddLsl(r8, rS, rD, 4)
		a.AddImm(r8, r8, 32, true)
		a.B(ready)
		a.Bind(up)
		a.AndImm(rD, rD, 0xffff, true)
		g.cmpMem(rD, rK, offClUpvals+8)
		a.BCond(HS, miss)
		a.Load(r8, rK, offClUpvals)
		a.LoadIdx(r8, r8, rD, true)
		a.Load(r8, r8, offUpSlot)
		a.Bind(ready)
		g.numMem(FReg(i), r8, miss)
	}
	sub, mul, result := a.NewLabel(), a.NewLabel(), a.NewLabel()
	a.Ubfx(rD, rJ, 0, 8)
	a.CmpImm(rD, int64(bytecode.RSub), true)
	a.BCond(EQ, sub)
	a.CmpImm(rD, int64(bytecode.RMul), true)
	a.BCond(EQ, mul)
	a.FArith(FAdd, 0, 0, 1)
	a.B(result)
	a.Bind(sub)
	a.FArith(FSub, 0, 0, 1)
	a.B(result)
	a.Bind(mul)
	a.FArith(FMul, 0, 0, 1)
	a.Bind(result)
	g.canon(0)
	g.storeB(0)
	a.Bind(getter)
	g.getterLeaf(miss)
	a.Bind(predicate)
	classify, classified, no, result := a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel()
	a.Store(rCtx, scr(sE), rC)
	a.Ubfx(rD, rJ, 16, 16)
	up, ready := a.NewLabel(), a.NewLabel()
	a.TstImm(rJ, 1<<32, true)
	a.BCond(NE, up)
	a.Ubfx(r9, rW, 8, 8)
	a.Cmp(rD, r9, true)
	a.BCond(LO, classify)
	a.MovImm(rC, 0) // A missing argument is undefined.
	a.B(classified)
	a.Bind(classify)
	a.AddLsl(rK, rS, rD, 4)
	a.AddImm(rK, rK, 32, true)
	typeMiss := a.NewLabel()
	a.B(ready)
	a.Bind(up)
	g.cmpMem(rD, rK, offClUpvals+8)
	a.BCond(HS, typeMiss)
	a.Load(rK, rK, offClUpvals)
	a.LoadIdx(rK, rK, rD, true)
	a.Load(rK, rK, offUpSlot)
	a.Bind(ready)
	savedExit := g.exit
	g.exit = typeMiss
	g.typeIndex(rK)
	g.exit = savedExit
	a.Bind(classified)
	a.Ubfx(rD, rJ, 8, 7)
	a.Cmp(rC, rD, true)
	a.BCond(NE, no)
	a.Load(r9, rCtx, ncTrue)
	a.B(result)
	a.Bind(no)
	a.Load(r9, rCtx, ncFalse)
	a.Bind(result)
	equal := a.NewLabel()
	a.TstImm(rJ, uint64(bytecode.RCmpTrue)<<8, true)
	a.BCond(NE, equal)
	a.MovImm(rT, 1<<8)
	a.Op(Eor, r9, r9, rT, true)
	a.Bind(equal)
	a.MovImm(r8, 0)
	g.regB(rW)
	g.storeValue()
	a.Bind(typeMiss)
	a.Load(rC, rCtx, scr(sE))
	a.B(miss)
}

// getterLeaf reads an own data property through the callee's cache. rJ is
// its descriptor, rK the closure, rC the call cache and rS the window.
func (g *armGen) getterLeaf(miss Label) {
	a := g.a
	a.LoadU8(rD, rC, offEKind)
	a.AndImm(rD, rD, uint64(^(regCallOut|regCallLeaf)&0xff), false)
	a.CmpImm(rD, int64(regCallThis), false)
	a.BCond(EQ, miss)
	a.Load(r9, rS, 16)
	g.cmpMem(r9, rCtx, ncObjBits)
	a.BCond(NE, miss)
	a.Load(r8, rS, 24)
	a.Load(rK, rK, offClCode)
	g.addMem(rK, rCtx, ncCCBase)
	a.Load(rK, rK, offCCIC)
	a.Ubfx(rD, rJ, 16, 16)
	a.MovImm(r9, uint64(size("propCache")))
	a.Mul(rD, rD, r9)
	a.Op(Add, rK, rK, rD, true)
	a.Load(r9, rK, off("propCache.ownShape"))
	g.cmpMem(r9, r8, offObjShape)
	a.BCond(NE, miss)
	a.LoadS32(rD, rK, off("propCache.idx"))
	a.Load(r9, r8, off("Object.valp"))
	a.AddLsl(rD, r9, rD, 4)
	a.Load(r9, rD, 0)
	a.Load(r8, rD, 8)
	result, length := a.NewLabel(), a.NewLabel()
	a.Ubfx(rD, rJ, 8, 8)
	a.CmpImm(rD, int64(bytecode.LeafGetThis), false)
	a.BCond(EQ, result)
	g.cmpMem(r9, rCtx, ncObjBits)
	a.BCond(NE, miss)
	a.CmpImm(rD, int64(bytecode.LeafGetThisLength), false)
	a.BCond(EQ, length)
	// A present numeric parameter that names a dense, non-hole element.
	a.Ubfx(rD, rJ, 32, 16)
	a.Ubfx(r9, rW, 8, 8)
	a.Cmp(rD, r9, true)
	a.BCond(HS, miss)
	a.AddLsl(rD, rS, rD, 4)
	a.AddImm(rD, rD, 32, true)
	g.numMem(0, rD, miss)
	a.Fcvtzs(rD, 0)
	a.ShiftImm(Lsr, r9, rD, 32, true)
	a.Cbnz(r9, miss, true)
	a.Scvtf(1, rD, true)
	a.FCmp(0, 1)
	a.BCond(NE, miss)
	a.LoadU16(r9, r8, offObjFlags)
	a.AndImm(r9, r9, uint64(objHasExt|objMappedArguments), false)
	a.CmpImm(r9, int64(objHasExt), false)
	a.BCond(NE, miss)
	g.cmpMem(rD, r8, sizeObj+8)
	a.BCond(HS, miss)
	a.Load(r9, r8, sizeObj)
	a.AddLsl(rD, r9, rD, 4)
	a.Load(r9, rD, 0)
	g.cmpMem(r9, rCtx, ncHole)
	a.BCond(EQ, miss)
	a.Load(r8, rD, 8)
	a.B(result)
	a.Bind(length)
	a.LoadU8(r9, r8, offObjClass)
	a.CmpImm(r9, int64(ClassArray), false)
	a.BCond(NE, miss)
	a.LoadU16(r9, r8, offObjFlags)
	a.AndImm(r9, r9, uint64(objHasExt|objHasSparseElements), false)
	a.CmpImm(r9, int64(objHasExt), false)
	a.BCond(NE, miss)
	a.Load(rD, r8, sizeObj+8)
	a.Scvtf(0, rD, true)
	g.storeB(0)
	a.Bind(result)
	g.regB(rW)
	g.storeValue()
}
