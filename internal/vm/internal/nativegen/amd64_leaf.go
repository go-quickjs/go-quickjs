// binaryLeaf answers a numeric binary leaf, this getter or typeof predicate
// without a frame. The cache in RCX is restored on a miss; RSI and RAX keep
// the window and instruction.
func (g *nativeGen) binaryLeaf(start, fallback Label) {
	a := g.a
	miss := a.NewLabel()
	a.Bind(start)
	a.Store(RDI, scr(sE), RCX)
	a.Load(RCX, R8, off("regCode.leafNative"))
	a.Op(Test, RCX, RCX, true)
	a.Jcc(CondE, miss)
	a.MovRR(R8, R9)
	a.Load(R9, RDI, ncRT)
	a.CmpMemImm8(R9, offRtInterrupt, 1)
	a.Jcc(CondLE, miss)
	getter := a.NewLabel()
	a.MovZX8(RDX, RCX)
	a.OpImm(Cmp, RDX, int32(bytecode.RGetProp), false)
	a.Jcc(CondE, getter)
	predicate := a.NewLabel()
	a.OpImm(Cmp, RDX, int32(bytecode.RJTypeof), false)
	a.Jcc(CondE, predicate)
	for i, shift := range []uint8{8, 32} {
		up, ready := a.NewLabel(), a.NewLabel()
		a.MovRR(RDX, RCX)
		a.ShiftImm(Shr, RDX, shift, true)
		a.OpImm(And, RDX, 0x1ffff, false)
		a.OpImm(Cmp, RDX, 1<<16, false)
		a.Jcc(CondAE, up)
		a.MovRR(R9, RAX)
		a.ShiftImm(Shr, R9, 8, true)
		a.MovZX8(R9, R9)
		a.Op(Cmp, RDX, R9, true)
		a.Jcc(CondAE, miss)
		a.ShiftImm(Shl, RDX, 4, true)
		a.LeaIdx(R9, RSI, RDX, 1, 32)
		a.Jmp(ready)
		a.Bind(up)
		a.OpImm(And, RDX, 0xffff, false)
		a.CmpMem(RDX, R8, offClUpvals+8, true)
		a.Jcc(CondAE, miss)
		a.Load(R9, R8, offClUpvals)
		a.LoadIdx(R9, R9, RDX, 8, 0)
		a.Load(R9, R9, offUpSlot)
		a.Bind(ready)
		a.CmpMem(R10, R9, 0, true)
		a.Jcc(CondBE, miss)
		a.LoadSD(XReg(i), R9, 0)
	}
	sub, mul, result := a.NewLabel(), a.NewLabel(), a.NewLabel()
	a.MovZX8(RDX, RCX)
	a.OpImm(Cmp, RDX, int32(bytecode.RSub), false)
	a.Jcc(CondE, sub)
	a.OpImm(Cmp, RDX, int32(bytecode.RMul), false)
	a.Jcc(CondE, mul)
	a.SSEOp(AddSD, 0, 1)
	a.Jmp(result)
	a.Bind(sub)
	a.SSEOp(SubSD, 0, 1)
	a.Jmp(result)
	a.Bind(mul)
	a.SSEOp(MulSD, 0, 1)
	a.Bind(result)
	g.canon(0)
	g.storeB(0)
	a.Bind(getter)
	g.getterLeaf(miss)
	a.Bind(predicate)
	classify, classified, no, result := a.NewLabel(), a.NewLabel(), a.NewLabel(), a.NewLabel()
	a.Store(RDI, scr(sV0), RCX)
	a.MovRR(RDX, RCX)
	a.ShiftImm(Shr, RDX, 16, true)
	a.OpImm(And, RDX, 0xffff, false)
	up, ready := a.NewLabel(), a.NewLabel()
	a.MovRR(R9, RCX)
	a.ShiftImm(Shr, R9, 32, true)
	a.OpImm(And, R9, 1, false)
	a.Jcc(CondNE, up)
	a.MovRR(R9, RAX)
	a.ShiftImm(Shr, R9, 8, true)
	a.MovZX8(R9, R9)
	a.Op(Cmp, RDX, R9, true)
	a.Jcc(CondB, classify)
	a.Op(Xor, RCX, RCX, false) // A missing argument is undefined.
	a.Jmp(classified)
	a.Bind(classify)
	a.ShiftImm(Shl, RDX, 4, true)
	a.LeaIdx(RDX, RSI, RDX, 1, 32)
	a.Op(Sub, RDX, R12, true)
	a.Jmp(ready)
	a.Bind(up)
	a.CmpMem(RDX, R8, offClUpvals+8, true)
	a.Jcc(CondAE, miss)
	a.Load(R8, R8, offClUpvals)
	a.LoadIdx(RDX, R8, RDX, 8, 0)
	a.Load(RDX, RDX, offUpSlot)
	a.Op(Sub, RDX, R12, true)
	a.Bind(ready)
	savedExit := g.exit
	g.exit = miss
	g.typeIndex(RDX)
	g.exit = savedExit
	a.Bind(classified)
	a.Load(RDX, RDI, scr(sV0))
	a.ShiftImm(Shr, RDX, 8, true)
	a.MovRR(R8, RDX)
	a.OpImm(And, R8, 0x7f, false)
	a.Op(Cmp, RCX, R8, true)
	a.Jcc(CondNE, no)
	a.Load(R9, RDI, ncTrue)
	a.Jmp(result)
	a.Bind(no)
	a.Load(R9, RDI, ncFalse)
	a.Bind(result)
	equal := a.NewLabel()
	a.OpImm(And, RDX, int32(bytecode.RCmpTrue), true)
	a.Jcc(CondNE, equal)
	a.OpImm(Xor, R9, 1<<8, true)
	a.Bind(equal)
	a.Op(Xor, R8, R8, false)
	g.decB(RDX)
	a.LeaIdx(RAX, R12, RDX, 1, 0)
	g.storeValue()
	a.Bind(miss)
	a.Load(RCX, RDI, scr(sE))
	a.Jmp(fallback)
}

// getterLeaf is arm64's frameless this getter. RCX is its descriptor,
// R8 the closure and RSI the window; binaryLeaf restores the cache on a miss.
func (g *nativeGen) getterLeaf(miss Label) {
	a := g.a
	a.Load(R9, RDI, scr(sE))
	a.LoadU8(RDX, R9, offEKind)
	a.OpImm(And, RDX, ^(regCallOut|regCallLeaf)&0xff, false)
	a.OpImm(Cmp, RDX, regCallThis, false)
	a.Jcc(CondE, miss)
	a.Load(R9, RSI, 16)
	a.CmpMem(R9, RDI, ncObjBits, true)
	a.Jcc(CondNE, miss)
	a.Load(R8, R8, offClCode)
	a.AddMem(R8, RDI, ncCCBase)
	a.Load(R8, R8, offCCIC)
	a.MovRR(RDX, RCX)
	a.ShiftImm(Shr, RDX, 16, true)
	a.OpImm(And, RDX, 0xffff, false)
	a.MovImm(R9, uint64(size("propCache")))
	a.Imul(RDX, R9)
	a.Op(Add, R8, RDX, true)
	a.Load(R9, RSI, 24)
	a.Load(RDX, R8, off("propCache.ownShape"))
	a.CmpMem(RDX, R9, offObjShape, true)
	a.Jcc(CondNE, miss)
	a.LoadS32(RDX, R8, off("propCache.idx"))
	a.ShiftImm(Shl, RDX, 4, true)
	a.AddMem(RDX, R9, off("Object.valp"))
	a.Load(R9, RDX, 0)
	a.Load(R8, RDX, 8)
	result, length := a.NewLabel(), a.NewLabel()
	a.MovRR(RDX, RCX)
	a.ShiftImm(Shr, RDX, 8, true)
	a.MovZX8(RDX, RDX)
	a.OpImm(Cmp, RDX, int32(bytecode.LeafGetThis), false)
	a.Jcc(CondE, result)
	a.CmpMem(R9, RDI, ncObjBits, true)
	a.Jcc(CondNE, miss)
	a.OpImm(Cmp, RDX, int32(bytecode.LeafGetThisLength), false)
	a.Jcc(CondE, length)
	a.ShiftImm(Shr, RCX, 32, true)
	a.LoadU8(RDX, RBX, 1)
	a.Op(Cmp, RCX, RDX, true)
	a.Jcc(CondAE, miss)
	a.ShiftImm(Shl, RCX, 4, true)
	a.LeaIdx(R9, RSI, RCX, 1, 32)
	a.CmpMem(R10, R9, 0, true)
	a.Jcc(CondBE, miss)
	a.LoadSD(0, R9, 0)
	a.Cvttsd2si(RDX, 0)
	a.MovRR(R9, RDX)
	a.ShiftImm(Shr, R9, 32, true)
	a.Op(Test, R9, R9, true)
	a.Jcc(CondNE, miss)
	a.Cvtsi2sd(1, RDX, true)
	a.SSEOp(UcomiSD, 0, 1)
	a.Jcc(CondNE, miss)
	a.Jcc(CondP, miss)
	a.LoadU16(R9, R8, offObjFlags)
	a.OpImm(And, R9, int32(objHasExt|objMappedArguments), false)
	a.OpImm(Cmp, R9, int32(objHasExt), false)
	a.Jcc(CondNE, miss)
	a.CmpMem(RDX, R8, sizeObj+8, true)
	a.Jcc(CondAE, miss)
	a.Load(R9, R8, sizeObj)
	a.ShiftImm(Shl, RDX, 4, true)
	a.Op(Add, RDX, R9, true)
	a.Load(R9, RDX, 0)
	a.CmpMem(R9, RDI, ncHole, true)
	a.Jcc(CondE, miss)
	a.Load(R8, RDX, 8)
	a.Jmp(result)
	a.Bind(length)
	a.LoadU8(R9, R8, offObjClass)
	a.OpImm(Cmp, R9, int32(ClassArray), false)
	a.Jcc(CondNE, miss)
	a.LoadU16(R9, R8, offObjFlags)
	a.OpImm(And, R9, int32(objHasExt|objHasSparseElements), false)
	a.OpImm(Cmp, R9, int32(objHasExt), false)
	a.Jcc(CondNE, miss)
	a.Load(RDX, R8, sizeObj+8)
	a.Cvtsi2sd(0, RDX, true)
	g.storeB(0)
	a.Bind(result)
	g.decB(RDX)
	a.LeaIdx(RAX, R12, RDX, 1, 0)
	g.storeValue()
}
