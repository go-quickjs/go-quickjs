// caseConvert maps a string to upper or lower case, character by character.
//
// Most characters have a single-character mapping the standard library knows.
// The rest are in the tables above, except the final sigma, whose mapping
// depends on what surrounds it rather than on what it is.
func caseConvert(s string, upper bool) string {
	table := specialLower
	simple := unicode.ToLower
	if upper {
		table, simple = specialUpper, unicode.ToUpper
	}
	var b strings.Builder
	b.Grow(len(s))
	for i, r := range s {
		if !upper && r == 'Σ' {
			b.WriteRune(finalSigma(s, i))
			continue
		}
		if to, ok := table[r]; ok {
			for _, c := range to {
				b.WriteRune(c)
			}
			continue
		}
		b.WriteRune(simple(r))
	}
	return b.String()
}

// finalSigma is what a capital sigma lowercases to at the given position.
//
// A sigma that ends a word becomes U+03C2, and one anywhere else becomes
// U+03C3. Ending a word means something cased comes before it and nothing cased
// comes after, with the characters that do not count either way -- accents,
// formatting, apostrophes -- skipped on both sides.
func finalSigma(s string, at int) rune {
	before := false
	for _, r := range reverseRunes(s[:at]) {
		if isCaseIgnorable(r) {
			continue
		}
		before = isCased(r)
		break
	}
	if !before {
		return 'σ'
	}
	for _, r := range s[at+len("Σ"):] {
		if isCaseIgnorable(r) {
			continue
		}
		if isCased(r) {
			return 'σ'
		}
		break
	}
	return 'ς'
}

// reverseRunes reads a string backwards, which the sigma rule needs.
func reverseRunes(s string) []rune {
	rs := []rune(s)
	for i, j := 0, len(rs)-1; i < j; i, j = i+1, j-1 {
		rs[i], rs[j] = rs[j], rs[i]
	}
	return rs
}

// isCased reports whether a character is one the sigma rule counts as a letter
// on either side of it.
func isCased(r rune) bool {
	return unicode.IsUpper(r) || unicode.IsLower(r) || unicode.IsTitle(r) ||
		unicode.In(r, unicode.Other_Lowercase, unicode.Other_Uppercase)
}

// isCaseIgnorable reports whether a character is one the sigma rule looks past.
func isCaseIgnorable(r rune) bool {
	switch r {
	case '\'', '’', '·', '·', '״', '‧', '︓', '﹕', '：':
		// The word-breaking punctuation that may sit inside a word.
		return true
	}
	return unicode.In(r, unicode.Mn, unicode.Me, unicode.Cf, unicode.Lm, unicode.Sk)
}
